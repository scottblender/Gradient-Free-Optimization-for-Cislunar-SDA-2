function test_reviewer2_paper_figures_configuration()
%TEST_REVIEWER2_PAPER_FIGURES_CONFIGURATION Audit curated manuscript output.

projectDir = fileparts(fileparts(mfilename('fullpath')));
styleText = string(fileread(fullfile(projectDir,'scripts','reviewer2_paper_style.m')));
geometryText = string(fileread(fullfile(projectDir,'scripts','plot_reviewer2_geometry_grid.m')));
selectorText = string(fileread(fullfile(projectDir,'scripts','select_reviewer2_representative_runs.m')));
wrapperText = string(fileread(fullfile(projectDir,'scripts','make_reviewer2_final_figures.m')));
runtimeFigureText = string(fileread(fullfile(projectDir,'scripts','make_reviewer2_runtime_figures.m')));
figureText = string(fileread(fullfile(projectDir,'scripts','make_reviewer2_curated_figures.m')));
runnerText = string(fileread(fullfile(projectDir,'scripts','run_reviewer2_results.m')));
introText = string(fileread(fullfile(projectDir,'scripts','plot_study_definition_figures.m')));
studyRunnerText = string(fileread(fullfile(projectDir,'scripts','run_study_definition_figures.m')));

requiredStyle = string({ ...
    'style.fontName = ''Times New Roman''', ...
    'style.fontSize = 12', ...
    'style.labelFontSize = 14', ...
    'style.geometryFigureWidth = 7.6', ...
    'style.geometryFigureHeight = 7.0', ...
    'style.geometryPlotPosition = [0.12 0.20 0.76 0.64]', ...
    'style.geometryAzimuth = -60', ...
    'style.geometryElevation = 25'});
assert_tokens(styleText,requiredStyle,'Shared paper style');

% Study-definition figures must consume the same shared style rather than
% duplicating a second set of typography/3-D/legend conventions.
requiredIntroStyle = string({ ...
    'reviewer2_paper_style()', ...
    'publication_figure(style.geometryFigureWidth,style.geometryFigureHeight)', ...
    'plotPosition = style.geometryPlotPosition', ...
    'view(ax,style.geometryAzimuth,style.geometryElevation)', ...
    'style.geometryXPadding', ...
    'style.geometryYPadding', ...
    'style.geometryZPadding', ...
    'style.geometryLegendGap', ...
    'format_study_legend', ...
    'legendHandle.Box = ''off''', ...
    '''FontName'',style.fontName', ...
    '''FontSize'',fontSize', ...
    '''LineWidth'',style.axisLineWidth', ...
    '''Box'',''off''', ...
    '''XGrid'',''off''', ...
    '''YGrid'',''off''', ...
    '''ZGrid'',''off''', ...
    '[departureOrbit,arrivalOrbit] = low_thrust_endpoint_orbits', ...
    '''Endpoint orbits'',''Transfer'',''Start'',''End'',''Moon'',''L1'',''L2'''});
assert_tokens(introText,requiredIntroStyle,'Study-definition figure renderer');
assert(~contains(introText,'box(ax,''on'')') && ...
    ~contains(introText,'box(ax1,''on'')') && ...
    ~contains(introText,'box(ax2,''on'')') && ...
    ~contains(introText,'grid(ax,''on'')') && ...
    ~contains(introText,'legendHandle.Box = ''on'''), ...
    'Study-definition figures must not enable axes/grid or legend boxes.');

% The public study-definition runner owns destructive cleanup. Its second
% input accepts the requested 1/0 flag and only clears the study-definition
% output directory before delegating to the existing renderer.
requiredStudyRunner = string({ ...
    'function outputs = run_study_definition_figures(inspectFigures,clearDirectory)', ...
    'clearDirectory = logical(clearDirectory)', ...
    'fullfile(paths.results,''study_definition_figures'')', ...
    'rmdir(outputDir,''s'')', ...
    'plot_study_definition_figures(inspectFigures)'});
assert_tokens(studyRunnerText,requiredStudyRunner,'Study-definition runner');

requiredSelector = string({ ...
    'closest to the 20-run group mean', ...
    'height(candidates) == 20', ...
    'GroupMeanObjective', ...
    'GroupStdObjective'});
assert_tokens(selectorText,requiredSelector,'Representative geometry selector');
assert(~contains(selectorText,'min(candidates.bestJ)'), ...
    'Final geometry must not select the best individual seed.');

requiredGeometry = string({ ...
    '7.6 x 7.0 inch canvas', ...
    'panelCells = cell(n,1)', ...
    'style.geometryPlotPosition', ...
    'PositionConstraint = ''innerposition''', ...
    'center_reference_legend', ...
    'common_geometry_limits', ...
    'panel.uniqueOrbitKeys = unique(panel.orbitKeys,''stable'')', ...
    '''Endpoint orbits''', ...
    'panel.nominalGateway = nominal_gateway_reference(panel.mu)', ...
    '''Nominal Gateway''', ...
    'box(ax,''off'')', ...
    'grid(ax,''off'')', ...
    'lgd.Box = ''off''', ...
    'FigureStem'});
assert_tokens(geometryText,requiredGeometry,'Geometry exporter');
assert(~contains(geometryText,'earthCenter') && ~contains(geometryText,'''Earth'''), ...
    'Final geometry figures must omit Earth.');
assert(contains(geometryText,"panel.nominalGateway(:,3),'--'") && ...
    contains(geometryText,'''DisplayName'',''Nominal Gateway'''), ...
    'Gateway-impulse result geometry must include the dashed nominal Gateway reference.');
assert(contains(geometryText,"plot3(ax,state(:,1),state(:,2),state(:,3),'-'"), ...
    'Observer periodic orbits must remain solid.');
assert(~contains(geometryText,'box(ax,''on'')') && ...
    ~contains(geometryText,'grid(ax,''on'')'), ...
    'Final trajectory axes must not enable boxes or grid lines.');

assert(contains(wrapperText,'make_reviewer2_runtime_figures') && ...
    contains(wrapperText,'make_reviewer2_curated_figures'), ...
    'Stable final-figure entry point must route runtime and curated studies correctly.');

requiredRuntimeFigures = string({ ...
    'runtime_1200_objective', ...
    'runtime_1200_runtime', ...
    'runtime_1200_convergence', ...
    'Optimizers are identified by the x-axis labels', ...
    'intentionally shows only the 20-run mean best-so-far history', ...
    'legend(ax,hBase,{''Baseline AO''}', ...
    'box(ax,''off'')', ...
    'grid(ax,''off'')', ...
    '''Box'',''off''', ...
    '''XGrid'',''off''', ...
    'plot_curve_overlay'});
assert_tokens(runtimeFigureText,requiredRuntimeFigures,'Runtime figure generator');
assert(~contains(runtimeFigureText,'legendHandles = b') && ...
    ~contains(runtimeFigureText,'legendLabels = optimizer_labels'), ...
    'Runtime bar charts must not pair one Bar handle with multiple optimizer legend labels.');
assert(~contains(runtimeFigureText,'dEnd = double(c.std'), ...
    'Runtime convergence must not draw terminal standard-deviation error bars.');
assert(~contains(runtimeFigureText,'box(ax,''on'')') && ...
    ~contains(runtimeFigureText,'grid(ax,''on'')'), ...
    'Runtime figures must not enable axes boxes or grid lines.');

requiredFigures = string({ ...
    'comparison_6000_objective', ...
    'comparison_6000_position_rmse', ...
    'comparison_6000_effective_sigma', ...
    'comparison_6000_stability', ...
    'comparison_6000_convergence_', ...
    'comparison_orbit_family_selection', ...
    'baseline_observer_', ...
    'baseline_gateway_duration_', ...
    'baseline_convergence_observers_', ...
    'baseline_convergence_duration_', ...
    'baseline_orbit_family_selection', ...
    'ga_screening_position_rmse', ...
    'ga_screening_effective_sigma', ...
    'ga_screening_stability', ...
    'ga_screening_event_count', ...
    'ga_screening_convergence_', ...
    'ga_objective_orbit_family_selection_', ...
    '["NHO","SHO","NNRHO","SNRHO","DRO"]', ...
    '["Combined","J_1","J_2","J_3"]', ...
    'build_comparison_family_data', ...
    'build_baseline_family_data', ...
    'build_objective_family_data', ...
    'plot_family_grouped_all_cases', ...
    'plot_objective_family_by_mission', ...
    'convergence figures show only the 20-run mean best-so-far curves', ...
    'box(ax,''off'')', ...
    'grid(ax,''off'')', ...
    '''Box'',''off''', ...
    '''XGrid'',''off''', ...
    '20-run mean +/- sample standard deviation'});
assert_tokens(figureText,requiredFigures,'Curated figure generator');

assert(~contains(figureText,'CoverageMean') && ~contains(figureText,'coverage_fraction'), ...
    'Coverage-fraction figures must not be generated.');
assert(~contains(figureText,'comparison_6000_runtime'), ...
    '6000-FE comparison runtime should remain table-only.');
assert(~contains(figureText,'ga_objective_position_rmse') && ...
    ~contains(figureText,'ga_objective_effective_sigma') && ...
    ~contains(figureText,'ga_objective_stability'), ...
    'Objective-component metric figures should be table-only.');
assert(~contains(figureText,'ga_screening_geometry') && ...
    ~contains(figureText,'ga_objective_geometry'), ...
    'Objective/screening trajectory figures should not be emitted.');
assert(count(figureText,'plot_reviewer2_geometry_grid(') == 2, ...
    'Trajectory figures should be generated only for comparison and baseline.');
assert(~contains(figureText,'tiledlayout('), ...
    'Final metrics must be standalone figures for LaTeX assembly.');
assert(~contains(figureText,'uncertainty_band('), ...
    'Final convergence must not use filled uncertainty bands.');
assert(~contains(figureText,'dEnd = double(c.std'), ...
    'Curated convergence must not draw terminal standard-deviation error bars.');
assert(~contains(figureText,'box(ax,''on'')') && ...
    ~contains(figureText,'grid(ax,''on'')'), ...
    'Curated Reviewer-2 figures must not enable axes boxes or grid lines.');

requiredRunner = string({ ...
    'COMPILED_REVIEWER_2_RESULTS', ...
    '"runtime_1200"', ...
    '"comparison"', ...
    '"baseline"', ...
    '"objective_screening"', ...
    'yyyyMMdd_HHmmss_SSS', ...
    'movefile', ...
    'make_reviewer2_final_figures(reports,true)', ...
    '20-run mean +/- sample standard deviation', ...
    'Trajectory figures are emitted only for comparison and baseline'});
assert_tokens(runnerText,requiredRunner,'Reviewer 2 results runner');
assert(~contains(runnerText,'fullfile(paths.results,studyName'), ...
    'Compiled Reviewer-2 outputs must not be written under results/.');

fprintf('Reviewer 2 paper-figure configuration passed.\n');
end


function assert_tokens(textValue,tokens,label)
for token = tokens
    assert(contains(textValue,token), ...
        '%s is missing required token: %s',label,token);
end
end