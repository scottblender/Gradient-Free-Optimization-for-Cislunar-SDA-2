function test_reviewer2_paper_figures_configuration()
%TEST_REVIEWER2_PAPER_FIGURES_CONFIGURATION Audit final manuscript rendering.

projectDir = fileparts(fileparts(mfilename('fullpath')));
styleText = string(fileread(fullfile(projectDir,'scripts','reviewer2_paper_style.m')));
geometryText = string(fileread(fullfile(projectDir,'scripts','plot_reviewer2_geometry_grid.m')));
selectorText = string(fileread(fullfile(projectDir,'scripts','select_reviewer2_representative_runs.m')));
paperText = string(fileread(fullfile(projectDir,'scripts','make_reviewer2_paper_figures.m')));
runnerText = string(fileread(fullfile(projectDir,'scripts','run_reviewer2_results.m')));
introText = string(fileread(fullfile(projectDir,'scripts','plot_study_definition_figures.m')));

requiredStyle = string({ ...
    'style.fontName = ''Times New Roman''', ...
    'style.fontSize = 12', ...
    'style.labelFontSize = 14', ...
    'style.figureWidth = 6.5', ...
    'style.geometryFigureWidth = 7.6', ...
    'style.geometryFigureHeight = 7.0', ...
    'style.geometryPlotPosition = [0.12 0.20 0.76 0.64]', ...
    'style.geometryLegendGap = 0.012', ...
    'style.geometryAzimuth = -37.5', ...
    'style.geometryElevation = 30', ...
    'style.geometryXPadding = 0.08', ...
    'style.geometryYPadding = 0.10', ...
    'style.geometryZPadding = 0.10'});
assert_tokens(styleText,requiredStyle,'Shared paper style');

% Verify the result style actually matches the successful introductory
% tracking-case construction rather than merely using similar prose.
assert(contains(introText,'publication_figure(7.6,7.0)') && ...
    contains(introText,'plotPosition = [0.12 0.20 0.76 0.64]') && ...
    contains(introText,'legendGap = 0.012') && ...
    contains(introText,'view(ax,-37.5,30)'), ...
    'Introductory 3-D reference layout changed; update result layout deliberately.');

requiredSelector = string({ ...
    'closest to the 20-run group mean', ...
    'height(candidates) == 20', ...
    'abs(double(candidates.bestJ)-double(mu))', ...
    'GroupMeanObjective', ...
    'GroupStdObjective', ...
    'ObjectiveDeviationFromMean', ...
    '"comparison"', ...
    '"baseline"', ...
    '"objective_screening"'});
assert_tokens(selectorText,requiredSelector,'Representative geometry selector');
assert(~contains(selectorText,'min(candidates.bestJ)'), ...
    'Geometry must not select the best individual seed.');

requiredGeometry = string({ ...
    '7.6 x 7.0 inch canvas', ...
    'style.geometryPlotPosition', ...
    'PositionConstraint = ''innerposition''', ...
    'prepare_reference_axes', ...
    'finalize_reference_axes', ...
    'center_reference_legend', ...
    'style.geometryLegendGap', ...
    'style.geometryAzimuth', ...
    'style.geometryElevation', ...
    'style.geometryXPadding', ...
    'style.geometryYPadding', ...
    'style.geometryZPadding', ...
    'panel.uniqueOrbitKeys = unique(panel.orbitKeys,''stable'')', ...
    '''Endpoint orbits''', ...
    'low_thrust_endpoint_orbits', ...
    'RepresentativeObjective', ...
    'GroupMeanObjective', ...
    'GroupStdObjective', ...
    'FigureStem', ...
    'print(fig,[base ''.eps''],''-depsc2'',''-painters'',''-r600'')'});
assert_tokens(geometryText,requiredGeometry,'Geometry exporter');
assert(~contains(geometryText,'earthCenter') && ...
    ~contains(geometryText,'earthRadius') && ...
    ~contains(geometryText,'''Earth'''), ...
    'Final geometry figures must omit Earth.');
assert(~contains(geometryText,'''--'''), ...
    'Final result geometry must use solid trajectory/orbit lines.');

requiredPaper = string({ ...
    'plot_curve_small_multiples', ...
    'final-FE +/- sample-standard-deviation bar', ...
    'runtime_1200_convergence', ...
    'comparison_6000_convergence_', ...
    'baseline_convergence_observers_', ...
    'baseline_convergence_duration_', ...
    'ga_screening_convergence_', ...
    'select_reviewer2_representative_runs', ...
    'comparison_6000_geometry_representative_runs.csv', ...
    'baseline_6000_geometry_representative_runs.csv', ...
    'ga_objective_screening_geometry_representative_runs.csv', ...
    'Total objective is intentionally omitted because J111/J100/J010/J001 are', ...
    'paper_final'});
assert_tokens(paperText,requiredPaper,'Final paper figure generator');
assert(~contains(paperText,'uncertainty_band('), ...
    'Final convergence figures must not overlay multiple uncertainty bands.');

requiredRunner = string({ ...
    'evalc(''run_reviewer2_runtime_pipeline(false)'')', ...
    'evalc(''run_reviewer2_comparison_pipeline(false)'')', ...
    'evalc(''run_reviewer2_baseline_pipeline(false)'')', ...
    'evalc(''run_reviewer2_objective_screening_pipeline(false)'')', ...
    'make_reviewer2_paper_figures(reports,true)', ...
    '20-run mean +/- sample standard deviation', ...
    'Best optimizer by target case, based on mean final objective', ...
    'representative geometry seeds are recorded only for traceability'});
assert_tokens(lower(runnerText),lower(requiredRunner),'Reviewer 2 results runner');

obsolete = [ ...
    "run_reviewer2_pipeline_pilot.m", ...
    "plot_reviewer2_best_trajectories.m", ...
    "plot_reviewer2_full_fe_convergence.m"];
for file = obsolete
    assert(~isfile(fullfile(projectDir,'scripts',file)), ...
        'Obsolete Reviewer 2 script remains: %s',file);
end

fprintf('Reviewer 2 paper-figure configuration passed.\n');
end


function assert_tokens(textValue,tokens,label)
for token = tokens
    assert(contains(textValue,token), ...
        '%s is missing required token: %s',label,token);
end
end
