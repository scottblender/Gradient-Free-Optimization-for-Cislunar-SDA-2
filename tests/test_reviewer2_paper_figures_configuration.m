function test_reviewer2_paper_figures_configuration()
%TEST_REVIEWER2_PAPER_FIGURES_CONFIGURATION Audit final manuscript rendering.

projectDir = fileparts(fileparts(mfilename('fullpath')));
styleText = string(fileread(fullfile(projectDir,'scripts','reviewer2_paper_style.m')));
geometryText = string(fileread(fullfile(projectDir,'scripts','plot_reviewer2_geometry_grid.m')));
paperText = string(fileread(fullfile(projectDir,'scripts','make_reviewer2_paper_figures.m')));
rankingText = string(fileread(fullfile(projectDir,'scripts','plot_reviewer2_optimizer_ranking.m')));
runtimeSummaryText = string(fileread(fullfile(projectDir,'scripts','plot_reviewer2_runtime_summary.m')));
screeningSummaryText = string(fileread(fullfile(projectDir,'scripts','plot_reviewer2_screening_summary.m')));
durationText = string(fileread(fullfile(projectDir,'scripts','plot_reviewer2_baseline_duration_matrix.m')));
runnerText = string(fileread(fullfile(projectDir,'scripts','run_reviewer2_results.m')));
objectiveText = string(fileread(fullfile( ...
    projectDir,'scripts','run_reviewer2_objective_screening_pipeline.m')));

requiredStyle = string({ ...
    'style.fontName = ''Times New Roman''', ...
    'style.fontSize = 12', ...
    'style.labelFontSize = 14', ...
    'style.optimizerOrder = ["GA","PSO","BAYESIAN","ABC","ACO"]', ...
    'reviewer2_target_color("LUNAR_GATEWAY")', ...
    'reviewer2_target_color("LOW_THRUST_TRANSFER")', ...
    'reviewer2_target_color("GATEWAY_IMPULSE")'});
assert_tokens(styleText,requiredStyle,'Shared paper style');

requiredGeometry = string({ ...
    'function details = plot_reviewer2_geometry_grid', ...
    'common axis', ...
    'common_geometry_limits', ...
    'reference_view', ...
    'azimuth = -37.5', ...
    'elevation = 30', ...
    'camzoom(ax,0.82)', ...
    '''LineStyle'',''-''', ...
    '''Endpoint orbits''', ...
    'low_thrust_endpoint_orbits', ...
    'MarkerFaceColor', ...
    'style.fontSize', ...
    'style.labelFontSize', ...
    'GridFigureStem'});
assert_tokens(geometryText,requiredGeometry,'Geometry grid exporter');
assert(~contains(geometryText,'earthCenter') && ...
    ~contains(geometryText,'earthRadius') && ...
    ~contains(geometryText,'''Earth'''), ...
    'Final geometry figures must omit Earth.');
assert(~contains(geometryText,'''--'''), ...
    'Final geometry figures must use solid trajectory/orbit lines.');

requiredPaper = string({ ...
    'function manifest = make_reviewer2_paper_figures', ...
    'runtime_1200_summary', ...
    'runtime_1200_convergence', ...
    'comparison_6000_summary', ...
    'comparison_6000_convergence_', ...
    'baseline_observer_trends_', ...
    'baseline_gateway_duration_trends', ...
    'baseline_convergence_observers_', ...
    'baseline_convergence_duration_', ...
    'ga_screening_summary_', ...
    'ga_screening_convergence_', ...
    'ga_objective_components_', ...
    'ga_objective_families_', ...
    'ga_objective_screening_trends.csv', ...
    'select_objective_geometry_runs', ...
    'plot_reviewer2_geometry_grid', ...
    'paper_figure_manifest.csv', ...
    'paper_final'});
assert_tokens(paperText,requiredPaper,'Final paper figure generator');
assert(contains(paperText, ...
    'Total objective is intentionally omitted because J111/J100/J010/J001 are'), ...
    'Objective-component plots must document why total objective is omitted.');

requiredRuntimeSummary = string({ ...
    'function stem = plot_reviewer2_runtime_summary', ...
    '1200 admitted FE', ...
    'BO: +%.1f%% vs best mean', ...
    'BO: %.1fx slower than fastest', ...
    'runtime_1200_summary', ...
    'style.fontSize'});
assert_tokens(runtimeSummaryText,requiredRuntimeSummary,'Runtime conclusion figure');

requiredScreeningSummary = string({ ...
    'function stems = plot_reviewer2_screening_summary', ...
    'Final best objective', ...
    'Position RMSE (km)', ...
    'Runtime to 6000 FE (s)', ...
    'Visibility-rule violations', ...
    'Screening ON', ...
    'Screening OFF', ...
    'style.fontSize'});
assert_tokens(screeningSummaryText,requiredScreeningSummary,'Screening conclusion figure');

requiredDuration = string({ ...
    'function stem = plot_reviewer2_baseline_duration_matrix', ...
    'counts = [3 5 7 10]', ...
    'periods = [1 3 5]', ...
    'measurements = ["ANGLES_ONLY","ANGLES_RANGE"]', ...
    'Final best objective', ...
    'Position RMSE (km)', ...
    'baseline_gateway_duration_by_observers', ...
    'style.fontSize'});
assert_tokens(durationText,requiredDuration,'Baseline duration interaction figure');

requiredRanking = string({ ...
    'function stem = plot_reviewer2_optimizer_ranking', ...
    'MeanObjectiveRank', ...
    'MissionWins', ...
    'comparison_6000_optimizer_ranking', ...
    'style.fontSize', ...
    'style.labelFontSize'});
assert_tokens(rankingText,requiredRanking,'Optimizer ranking figure');

requiredRunner = string({ ...
    'run_reviewer2_runtime_pipeline(false)', ...
    'run_reviewer2_comparison_pipeline(false)', ...
    'run_reviewer2_baseline_pipeline(false)', ...
    'run_reviewer2_objective_screening_pipeline(false)', ...
    'make_reviewer2_paper_figures(reports,true)', ...
    'plot_reviewer2_runtime_summary(reports.runtime,true)', ...
    'plot_reviewer2_screening_summary(reports.objective_screening,true)', ...
    'plot_reviewer2_baseline_duration_matrix(reports.baseline,true)', ...
    'plot_reviewer2_optimizer_ranking(reports.comparison,true)', ...
    'paper_final'});
assert_tokens(runnerText,requiredRunner,'Reviewer 2 results runner');

requiredObjective = string({ ...
    'expectedRuns = expectedGroups*numel(seeds)', ...
    'combined_on', ...
    'combined_off', ...
    'j1_only', ...
    'j2_only', ...
    'j3_only', ...
    'build_screening_contrasts', ...
    'build_component_winners', ...
    'build_family_selection'});
assert_tokens(objectiveText,requiredObjective,'Objective/screening processor');
assert(5*3*20 == 300,'GA objective/screening study must contain 300 runs.');

obsolete = [ ...
    "run_reviewer2_pipeline_pilot.m", ...
    "plot_reviewer2_best_trajectories.m", ...
    "plot_reviewer2_full_fe_convergence.m"];
for file = obsolete
    assert(~isfile(fullfile(projectDir,'scripts',file)), ...
        'Obsolete Reviewer 2 script remains: %s',file);
end

fprintf('Reviewer 2 paper-figure configuration passed.\n');
end


function assert_tokens(textValue,tokens,label)
for token = tokens
    assert(contains(textValue,token), ...
        '%s is missing required token: %s',label,token);
end
end
