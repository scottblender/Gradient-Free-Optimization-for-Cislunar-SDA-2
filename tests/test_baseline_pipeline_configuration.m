function test_baseline_pipeline_configuration()
%TEST_BASELINE_PIPELINE_CONFIGURATION Audit completed baseline processing.

projectDir = fileparts(fileparts(mfilename('fullpath')));
pipelineText = string(fileread(fullfile( ...
    projectDir,'scripts','run_reviewer2_baseline_pipeline.m')));
launcherText = string(fileread(fullfile( ...
    projectDir,'scripts','batch','run_baseline_soo.ps1')));
geometryText = string(fileread(fullfile( ...
    projectDir,'scripts','plot_reviewer2_geometry_grid.m')));

requiredPipeline = string({ ...
    'budget = 6000', ...
    'plotStartFE = 60', ...
    'seeds = 0:19', ...
    'measurements = ["ANGLES_ONLY","ANGLES_RANGE"]', ...
    'missions = ["LUNAR_GATEWAY","LOW_THRUST_TRANSFER","GATEWAY_IMPULSE"]', ...
    'observerCounts = [3 5 7 10]', ...
    'gatewayPeriods = [1 3 5]', ...
    'studyID = "reviewer2_baseline_v1"', ...
    'baselineRoot = fullfile(paths.runs,''BASELINE'')', ...
    'expectedGroups = 2*(4*3 + 4 + 4)', ...
    'expectedRuns = expectedGroups*numel(seeds)', ...
    'process_fe_convergence', ...
    'validate_baseline_factorial', ...
    'baseline_6000_trends.csv'});
assert_tokens(pipelineText,requiredPipeline,'Baseline processing pipeline');

requiredLauncher = string({ ...
    '$StudyId = "reviewer2_baseline_v1"', ...
    '$MeasurementModels = @("ANGLES_ONLY", "ANGLES_RANGE")', ...
    '$ObserverCounts = @(3, 5, 7, 10)', ...
    '$GatewayPeriods = @(1, 3, 5)', ...
    '$env:USE_SCREENING = "1"', ...
    '$env:USE_J1 = "1"', ...
    '$env:USE_J2 = "1"', ...
    '$env:USE_J3 = "1"'});
assert_tokens(launcherText,requiredLauncher,'Baseline launcher');

requiredGeometry = string({ ...
    '7.6 x 7.0 inch canvas', ...
    'style.geometryPlotPosition', ...
    'PositionConstraint = ''innerposition''', ...
    'prepare_reference_axes', ...
    'center_reference_legend', ...
    'style.geometryLegendGap', ...
    'panel.uniqueOrbitKeys = unique(panel.orbitKeys,''stable'')', ...
    'tPlot = linspace(0,period,360)', ...
    'plot3(ax,state(:,1),state(:,2),state(:,3),''-''', ...
    'style.geometryAzimuth', ...
    'style.geometryElevation', ...
    'style.geometryXPadding', ...
    'style.geometryYPadding', ...
    'style.geometryZPadding', ...
    'RepresentativeObjective', ...
    'GroupMeanObjective', ...
    'GroupStdObjective'});
assert_tokens(geometryText,requiredGeometry,'Shared constellation geometry exporter');
assert(~contains(geometryText,'earthCenter') && ...
    ~contains(geometryText,'earthRadius') && ...
    ~contains(geometryText,'''Earth'''), ...
    'Earth must be omitted from final baseline geometry plots.');
assert(~contains(geometryText,'''--'''), ...
    'Baseline geometry panels must not draw dashed trajectory/orbit lines.');

assert(2*(4*3+4+4)*20 == 800);
fprintf('Baseline pipeline configuration passed.\n');
end


function assert_tokens(textValue,tokens,label)
for token = tokens
    assert(contains(textValue,token), ...
        '%s is missing required token: %s',label,token);
end
end
