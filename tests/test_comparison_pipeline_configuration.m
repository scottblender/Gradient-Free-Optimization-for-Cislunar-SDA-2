function test_comparison_pipeline_configuration()
%TEST_COMPARISON_PIPELINE_CONFIGURATION Audit the 6000-FE result processor.

projectDir = fileparts(fileparts(mfilename('fullpath')));
pipelineText = string(fileread(fullfile( ...
    projectDir,'scripts','run_reviewer2_comparison_pipeline.m')));
launcherText = string(fileread(fullfile( ...
    projectDir,'scripts','batch','run_comparison_soo.ps1')));
geometryText = string(fileread(fullfile( ...
    projectDir,'scripts','plot_reviewer2_geometry_grid.m')));

requiredPipeline = string({ ...
    'function report = run_reviewer2_comparison_pipeline(saveFigures)', ...
    'budget = 6000', ...
    'seeds = 0:19', ...
    'optimizers = ["GA","PSO","ABC","ACO"]', ...
    'missions = ["LUNAR_GATEWAY","LOW_THRUST_TRANSFER","GATEWAY_IMPULSE"]', ...
    'studyID = "reviewer2_comparison_v1"', ...
    'comparisonRoot = fullfile(paths.runs,''COMPARISON'')', ...
    'expectedRuns = numel(optimizers)*numel(missions)*numel(seeds)', ...
    'process_fe_convergence', ...
    'plotStartFE = 60', ...
    'comparison_6000_best_by_mission.csv', ...
    'select_best_geometry_runs', ...
    'plot_reviewer2_constellation_geometry', ...
    'comparison_6000_geometry_selected_runs.csv', ...
    'comparison_6000_geometry_details.csv'});
assert_tokens(pipelineText,requiredPipeline,'Comparison processing pipeline');

obsolete = string({ ...
    'runScreeningSensitivity', ...
    'build_screening_sensitivity', ...
    'SCREENING_SENSITIVITY_GA_6000', ...
    'evaluate_screening_off', ...
    'plot_screening_metric', ...
    'comparison_6000_screening_on_off'});
for token = obsolete
    assert(~contains(pipelineText,token), ...
        'Obsolete post-processing screening diagnostic remains: %s',token);
end

requiredLauncher = string({ ...
    '$StudyId = "reviewer2_comparison_v1"', ...
    '$Algs = @("GA", "PSO", "ABC", "ACO")', ...
    '$MeasurementModels = @("ANGLES_ONLY")', ...
    '$MissionTypes = @("LUNAR_GATEWAY", "LOW_THRUST_TRANSFER", "GATEWAY_IMPULSE")', ...
    '$ObserverCounts = @(3)', ...
    '$GatewayPeriods = @(1)', ...
    '$env:USE_SCREENING = "1"'});
assert_tokens(launcherText,requiredLauncher,'Full comparison launcher');

requiredGeometry = string({ ...
    'function details = plot_reviewer2_geometry_grid', ...
    'panel.uniqueOrbitKeys = unique(panel.orbitKeys,''stable'')', ...
    '''LineStyle'',''-''', ...
    'common_geometry_limits', ...
    'azimuth = -37.5', ...
    'elevation = 30', ...
    'camzoom(ax,0.82)', ...
    'reviewer2_paper_style', ...
    '''Endpoint orbits''', ...
    'low_thrust_endpoint_orbits', ...
    'GridFigureStem'});
assert_tokens(geometryText,requiredGeometry,'Constellation geometry exporter');
assert(~contains(geometryText,'earthCenter') && ...
    ~contains(geometryText,'earthRadius') && ...
    ~contains(geometryText,'''Earth'''), ...
    'Earth must be omitted from final comparison geometry plots.');
assert(~contains(geometryText,'''--'''), ...
    'Comparison geometry panels must not draw dashed trajectory/orbit lines.');

fprintf('Comparison pipeline configuration passed.\n');
end


function assert_tokens(textValue,tokens,label)
for token = tokens
    assert(contains(textValue,token), ...
        '%s is missing required token: %s',label,token);
end
end
