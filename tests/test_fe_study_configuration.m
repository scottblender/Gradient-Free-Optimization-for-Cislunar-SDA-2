function test_fe_study_configuration()
%TEST_FE_STUDY_CONFIGURATION Audit the final manuscript FE study entry points.
%
% This test is intentionally limited to the four retained optimization
% studies and the common FE accounting/processing path. Manuscript rendering
% is audited separately by test_reviewer2_paper_figures_configuration.

projectDir = fileparts(fileparts(mfilename('fullpath')));
runText = string(fileread(fullfile(projectDir,'run_opt.m')));
guiText = string(fileread(fullfile(projectDir,'launch_optimization_gui.m')));
baselineText = string(fileread(fullfile( ...
    projectDir,'scripts','batch','run_baseline_soo.ps1')));
comparisonText = string(fileread(fullfile( ...
    projectDir,'scripts','batch','run_comparison_soo.ps1')));
runtimeText = string(fileread(fullfile( ...
    projectDir,'scripts','batch','run_runtime_comparison_1200_soo.ps1')));
objectiveText = string(fileread(fullfile( ...
    projectDir,'scripts','batch','run_ga_objective_screening_soo.ps1')));
saveText = string(fileread(fullfile( ...
    projectDir,'scripts','save_tracking_results.m')));
processText = string(fileread(fullfile( ...
    projectDir,'scripts','process_fe_convergence.m')));

launchers = [baselineText,comparisonText,runtimeText,objectiveText];
launcherNames = ["baseline","comparison","runtime","objective/screening"];

% The reviewer-facing workflow is FE-limited only.
assert(~contains(runText,"MAX_ITERS") && ~contains(guiText,"MAX_ITERS"), ...
    'run_opt/GUI must not expose an iteration fallback.');
for k = 1:numel(launchers)
    assert(~contains(launchers(k),"MAX_ITERS"), ...
        '%s launcher must not expose an iteration fallback.',launcherNames(k));
end

supported = ["GA","PSO","BAYESIAN","ABC","ACO"];
for optimizer = supported
    dq = string(sprintf('"%s"',optimizer));
    sq = string(sprintf('''%s''',optimizer));
    assert(contains(runText,dq) || contains(runText,sq), ...
        'run_opt is missing optimizer %s.',optimizer);
end
assert(~contains(runText,"GAMULTIOBJ") && ~contains(runText,"DMOPSO") && ...
    ~contains(guiText,"GAMULTIOBJ") && ~contains(guiText,"DMOPSO"), ...
    'Obsolete multiobjective optimizer branches remain.');

missions = ["LUNAR_GATEWAY","LOW_THRUST_TRANSFER","GATEWAY_IMPULSE"];
for mission = missions
    token = string(sprintf('"%s"',mission));
    assert(contains(runText,token), ...
        'run_opt is missing mission %s.',mission);
    assert(contains(baselineText,token) && contains(comparisonText,token) && ...
        contains(objectiveText,token), ...
        'A three-mission study is missing %s.',mission);
end

% Final full-study definitions.
assert_tokens(baselineText,string({ ...
    '$StudyId = "reviewer2_baseline_v1"', ...
    '[int]$EvalBudget = 6000', ...
    '[int[]]$Seeds = (0..19)', ...
    '$MeasurementModels = @("ANGLES_ONLY", "ANGLES_RANGE")', ...
    '$ObserverCounts = @(3, 5, 7, 10)', ...
    '$GatewayPeriods = @(1, 3, 5)', ...
    '$env:USE_SCREENING = "1"', ...
    '$env:USE_J1 = "1"', ...
    '$env:USE_J2 = "1"', ...
    '$env:USE_J3 = "1"'}), 'Baseline');

assert_tokens(comparisonText,string({ ...
    '$StudyId = "reviewer2_comparison_v1"', ...
    '[int]$EvalBudget = 6000', ...
    '[int[]]$Seeds = (0..19)', ...
    '$Algs = @("GA", "PSO", "ABC", "ACO")', ...
    '$MeasurementModels = @("ANGLES_ONLY")', ...
    '$MissionTypes = @("LUNAR_GATEWAY", "LOW_THRUST_TRANSFER", "GATEWAY_IMPULSE")', ...
    '$ObserverCounts = @(3)', ...
    '$GatewayPeriods = @(1)', ...
    '$env:USE_SCREENING = "1"'}), 'Comparison');

assert_tokens(runtimeText,string({ ...
    '$StudyId = "reviewer2_runtime_comparison_1200_v1"', ...
    '$StudyFolder = "RUNTIME_COMPARISON_1200"', ...
    '$EvalBudget = 1200', ...
    '[int[]]$Seeds = (0..19)', ...
    '$Algs = @("GA", "PSO", "BAYESIAN", "ABC", "ACO")', ...
    '$MissionType = "LUNAR_GATEWAY"', ...
    '$MeasModel = "ANGLES_ONLY"', ...
    '$NumObservers = 3', ...
    '$NPeriods = 1', ...
    '$TotalRuns = $Algs.Count * $Seeds.Count'}), 'Runtime');

assert_tokens(objectiveText,string({ ...
    '$StudyId = "reviewer2_ga_objective_screening_v1"', ...
    '$StudyFolder = "GA_OBJECTIVE_SCREENING"', ...
    '[int]$EvalBudget = 6000', ...
    '[int[]]$Seeds = (0..19)', ...
    '$env:OPTIMIZER_MODE = "GA"', ...
    '$env:MEAS_MODEL = "ANGLES_ONLY"', ...
    '$env:NUM_OBSERVERS = "3"', ...
    '$env:NPERIODS = "1"', ...
    'Code = "combined_on"', ...
    'Code = "combined_off"', ...
    'Code = "j1_only"', ...
    'Code = "j2_only"', ...
    'Code = "j3_only"'}), 'Objective/screening');

% The comparison pilot remains only as a launcher-level dress rehearsal; the
% deleted monolithic pilot postprocessor is intentionally not part of the
% final repository.
assert(contains(comparisonText,'[switch]$Pilot') && ...
    contains(comparisonText,'COMPARISON_PILOT_1200') && ...
    contains(comparisonText,'reviewer2_comparison_pilot_1200_v1') && ...
    contains(comparisonText,'$EvalBudget = 1200') && ...
    contains(comparisonText, ...
        '$Algs = @("GA", "PSO", "BAYESIAN", "ABC", "ACO")'), ...
    'Comparison pilot must retain the isolated five-method 1200-FE dress rehearsal.');
assert(contains(baselineText,'[switch]$Pilot') && contains(baselineText,'BASELINE_PILOT'), ...
    'Baseline pilot is missing.');
assert(contains(objectiveText,'[switch]$Pilot') && ...
    contains(objectiveText,'GA_OBJECTIVE_SCREENING_PILOT'), ...
    'Objective/screening pilot is missing.');

% Common scientific settings and deterministic measurement noise.
commonTokens = string({ ...
    '$env:MAX_EVALS', ...
    '$env:MEAS_NOISE_SEED', ...
    '$env:MAKE_PLOTS = "0"', ...
    '$env:IMPULSE_DV_MPS = "10"', ...
    '$env:IMPULSE_DURATION_TU = "1.5"', ...
    '$env:USE_PARALLEL_OPT = "1"'});
for k = 1:numel(launchers)
    assert_tokens(launchers(k),commonTokens,launcherNames(k));
end

% Completed deterministic folders are skipped; partial runs are archived and
% rerun rather than overwritten.
resumeTokens = string({ ...
    '$hasState -and $hasTracking', ...
    '_INCOMPLETE_RUNS', ...
    'Move-Item -Path $RunDir -Destination $archiveDir', ...
    'Skipping completed run', ...
    'Write-Progress'});
for k = 1:numel(launchers)
    assert_tokens(launchers(k),resumeTokens,launcherNames(k));
end

% Parallel bayesopt can finish already-dispatched work after the admitted FE
% boundary. Only the prescribed FE affect bestJ/history and equal-budget time.
assert_tokens(runText,string({ ...
    'parallel_overflow_truncate_v1', ...
    'bo_outfun', ...
    'OPT_BO_BUDGET_RUNTIME', ...
    'ObjectiveTrace(1:FE_BUDGET)', ...
    'XTrace(1:FE_BUDGET,:)', ...
    'parallelOverflowEvaluations', ...
    'budgetRuntime_s', ...
    'solverWallRuntime_s'}), 'run_opt Bayesian accounting');
assert_tokens(processText,string({ ...
    'parallelOverflowEvaluations', ...
    'budgetRuntime_s', ...
    'solverWallRuntime_s', ...
    'opt == "BAYESIAN"'}), 'FE processor Bayesian accounting');

assert(contains(guiText,'ScreenSize') && contains(guiText,'gaugeFE'), ...
    'The launcher must use a screen-aware layout and FE progress gauge.');
assert(~contains(guiText,'Mean det(P_pos)') && ...
    ~contains(saveText,'mean_detPpos_km6'), ...
    'The legacy mean determinant result must not be stored or displayed.');

% Final run counts used in the manuscript campaigns.
assert(2*(4*3+4+4)*20 == 800,'Baseline run count changed.');
assert(4*3*20 == 240,'Full comparison run count changed.');
assert(5*20 == 100,'Focused runtime run count changed.');
assert(5*3*20 == 300,'Objective/screening run count changed.');

fprintf('FE study configuration passed.\n');
end

function assert_tokens(textValue,tokens,label)
for token = tokens
    assert(contains(textValue,token), ...
        '%s is missing required token: %s',label,token);
end
end
